/* Bounded display resources and library DOM; no performance thresholds tied to one PC. */
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
(async()=>{
 const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
 const page=await browser.newPage({viewport:{width:1320,height:1000},reducedMotion:'reduce'});
 const errors=[],originalArtRequests=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(/\/assets\/constellation\/\d{2}-[^/]+\.png$/.test(r.url()))originalArtRequests.push(r.url())});
 await page.goto(pathToFileURL(path.resolve(__dirname,'../src/VocabDesk/Website/index.html')).href+'?desktop=1');
 await page.waitForFunction(()=>window.WordOrbitConstellation?.snapshot().nodes.length===22&&[...document.querySelectorAll('.celestial-object img')].every(i=>i.complete&&i.naturalWidth));
 const dimensions=await page.locator('.celestial-object img').evaluateAll(images=>images.map(i=>[i.naturalWidth,i.naturalHeight]));
 assert.equal(dimensions.length,22);
 assert.ok(dimensions.every(([w,h])=>w<=512&&h<=512));
 assert.ok(dimensions.filter(([w])=>w===384).length>=20);
 // A new largest topic reuses the single star asset; two DOM uses do not mean
 // two distinct large source images or a second high-resolution asset download.
 const starSources=await page.locator('.celestial-object img').evaluateAll(images=>[...new Set(images.filter(i=>i.naturalWidth===512).map(i=>i.src))]);
 assert.equal(starSources.length,1);
 assert.deepEqual(originalArtRequests,[],'Full-resolution originals are not loaded by the UI');
 assert.equal(await page.locator('.wordorbit-mark').evaluate(i=>i.naturalWidth),128);
 const catalogCount=await page.evaluate(()=>state.words.length);
 const lastWord=await page.evaluate(()=>state.words.at(-1).word);
 await page.evaluate(()=>showView('library'));
 assert.equal(await page.locator('#wordTable .word-row').count(),80);
 assert.match(await page.locator('#libraryPager').innerText(),new RegExp('共 '+catalogCount+' 词'));
 const firstPageFirst=await page.locator('.word-main strong').first().textContent();
 await page.getByRole('button',{name:'下一页',exact:true}).click();
 assert.equal(await page.locator('#wordTable .word-row').count(),80);
 assert.notEqual(await page.locator('.word-main strong').first().textContent(),firstPageFirst);
 await page.getByRole('button',{name:'末页',exact:true}).click();
 assert.equal(await page.locator('#wordTable .word-row').count(),catalogCount%80||80);
 assert.equal(await page.locator('.word-main strong').last().textContent(),lastWord);
 assert.equal(await page.getByRole('button',{name:'下一页',exact:true}).isDisabled(),true);
 await page.locator('#searchInput').fill(lastWord);
 assert.ok(await page.locator('.word-main strong').allTextContents().then(words=>words.includes(lastWord)),'Search covers the full catalog, not only the current page');
 assert.match(await page.locator('#libraryPager').innerText(),/第 1\//);
 await page.locator('#searchInput').fill('zzzz-no-such-vocabulary-entry-zzzz');
 assert.equal(await page.locator('#wordTable .word-row').count(),0);
 assert.equal(await page.locator('#libraryPager').isVisible(),false);
 await page.locator('#searchInput').fill('');
 await page.locator('#libraryChapter').selectOption('时间日期');
 const topicCount=await page.evaluate(()=>state.words.filter(w=>w.chapter==='时间日期').length);
 assert.equal(await page.locator('#wordTable .word-row').count(),topicCount);
 await page.locator('#libraryChapter').selectOption('all');
 await page.getByRole('button',{name:'下一页',exact:true}).click();
 const edited=await page.locator('.edit-word').first().getAttribute('data-id');
 await page.locator('.edit-word').first().click();
 await page.locator('#editNotes').fill('memory-test-specific-note');
 await page.locator('#editForm button[type="submit"]').click();
 assert.equal(await page.evaluate(id=>state.words.find(w=>w.id===id).notes,edited),'memory-test-specific-note');
 assert.equal(await page.locator('.edit-word').first().getAttribute('data-id'),edited,'Editing retains the current page');
 await page.locator('.fav-toggle').first().click();
 assert.equal(await page.evaluate(id=>state.favorites.includes(id),edited),true);
 await page.locator('#libraryStatus').selectOption('favorite');
 assert.equal(await page.locator('#wordTable .word-row').count(),1);
 await page.locator('.fav-toggle').click();
 assert.equal(await page.locator('#wordTable .word-row').count(),0);
 await page.locator('#libraryStatus').selectOption('all');
 const known={records:await page.evaluate(()=>JSON.stringify(state.records)),attempts:await page.evaluate(()=>JSON.stringify(state.attempts)),count:await page.evaluate(()=>state.words.length)};
 for(let i=0;i<5;i++){
   await page.evaluate(()=>showView('home'));
   assert.equal(await page.locator('#wordTable .word-row').count(),0,'Leaving library releases rendered rows');
   await page.evaluate(()=>showView('library'));
   assert.ok(await page.locator('#wordTable .word-row').count()<=80);
 }
 assert.equal(await page.evaluate(()=>JSON.stringify(state.records)),known.records);
 assert.equal(await page.evaluate(()=>JSON.stringify(state.attempts)),known.attempts);
 assert.equal(await page.evaluate(()=>state.words.length),known.count);
 await page.reload();
 assert.equal(await page.evaluate(id=>state.words.find(w=>w.id===id).notes,edited),'memory-test-specific-note','Personal notes remain persisted');
 assert.equal(await page.locator('#wordTable .word-row').count(),0);
 assert.equal(await page.locator('.celestial-body').count(),22);
  await page.evaluate(()=>showView('library'));
  await page.setViewportSize({width:390,height:1000});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false,'Paged library fits narrow windows');
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({passed:true,displayImages:22,maxImageDimension:512,libraryPageSize:80,checks:['full-catalog search','pagination boundaries','filter reset','empty results','notes/edit','favorites','DOM release','record preservation','reload']},null,2));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
